use std::path::Path;

/// Audio formats symphonia decodes for us (see Cargo features).
const AUDIO: &[&str] = &["mp3", "wav", "flac", "ogg", "m4a"];

fn main() {
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        let mut res = winresource::WindowsResource::new();
        res.set_icon("icons/app.ico");
        res.compile().expect("embed app icon");
    }
    bake_bench_clips();
}

/// bench/<id>.<audio> + bench/<id>.txt  →  $OUT_DIR/clips.rs:
///   pub static BUILTIN: &[(&str /*id*/, &str /*ext*/, &[u8] /*audio*/, &str /*script*/)]
/// A clip without a script is skipped with a warning: no script, no grading.
fn bake_bench_clips() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("bench");
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut clips: Vec<_> = std::fs::read_dir(&dir).into_iter().flatten().flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().and_then(|e| e.to_str())
            .is_some_and(|e| AUDIO.contains(&e.to_ascii_lowercase().as_str())))
        .collect();
    clips.sort();

    let rows: String = clips.iter().filter_map(|audio| {
        let id = audio.file_stem()?.to_str()?;
        let ext = audio.extension()?.to_str()?.to_ascii_lowercase();
        let script = audio.with_extension("txt");
        if !script.is_file() {
            println!("cargo:warning=bench/{id}.{ext} has no bench/{id}.txt script; skipped");
            return None;
        }
        println!("cargo:rerun-if-changed={}", audio.display());
        println!("cargo:rerun-if-changed={}", script.display());
        Some(format!("    ({id:?}, {ext:?}, include_bytes!({:?}), include_str!({:?})),\n",
            audio.display().to_string(), script.display().to_string()))
    }).collect();

    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("clips.rs");
    std::fs::write(out, format!(
        "// generated by build.rs from bench/ — do not edit\n\
         pub static BUILTIN: &[(&str, &str, &[u8], &str)] = &[\n{rows}];\n"))
        .expect("write clips.rs");
}
